import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const dist=path.resolve(process.argv[2]||'dist');
const dir=path.join(dist,'vendor','smartrisk-consultoria');
const registrySource=fs.readFileSync(path.join(dir,'ecuador-market-222.js'),'utf8');
const businessSource=fs.readFileSync(path.join(dir,'business-market.js'),'utf8');
const index=fs.readFileSync(path.join(dir,'index.html'),'utf8');
const context={window:{}};
vm.runInNewContext(registrySource,context);
const market=context.window.SmartRiskEcuadorMarket;
assert.ok(market,'No se expuso SmartRiskEcuadorMarket');
assert.equal(market.records.length,222,'El registro debe contener 222 cantones');
assert.equal(market.provinces.length,24,'El registro debe cubrir 24 provincias');
assert.equal(new Set(market.records.map(x=>x.dpa)).size,222,'Los códigos DPA deben ser únicos');
assert.equal(market.get('Loja','Loja').urbanOfficialHa,6060.18,'Loja debe conservar el área urbana oficial verificada');
assert.equal(market.get('Morona Santiago','Sevilla Don Bosco').dpa,'1413','Debe incluir el cantón 222 Sevilla Don Bosco');
for(const [province,cantons] of Object.entries(market.byProvince)) assert.ok(cantons.length>0,`Provincia sin cantones: ${province}`);
assert.match(businessSource,/Radar de negocios · Mercado nacional/);
assert.match(businessSource,/Ajuste estratégico/);
assert.match(businessSource,/Riesgo de cobro/);
assert.match(businessSource,/GO \/ NO-GO/);
assert.match(businessSource,/localStorage/,'La valoración comercial debe conservarse en modo evaluación');
const order=['consultoria-core.js','national-qa-patch.js','ecuador-market-222.js','territorial-defaults.js','business-market.js','business-ui-fix.js'].map(x=>index.indexOf(x));
assert.ok(order.every(x=>x>=0),'Falta un script del módulo comercial en index.html');
assert.deepEqual([...order].sort((a,b)=>a-b),order,'El orden de carga de scripts no es el esperado');
console.log('PASS Consultoría Mercado 222: 24 provincias, 222 GAD cantonales, Loja oficial, GO/NO-GO y trazabilidad territorial.');
